BASE_DIR = Path(__file__).resolve().parent.parent


def env_bool(name, default=False):
    value = os.getenv(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


IS_RENDER = bool(os.getenv("RENDER"))

SECRET_KEY = os.getenv("GAMEHUB_SECRET_KEY") or os.getenv("SECRET_KEY")
if not SECRET_KEY:
    if IS_RENDER:
        raise RuntimeError("GAMEHUB_SECRET_KEY (or SECRET_KEY) must be set on Render.")
    SECRET_KEY = "dev-only-change-me-before-production"

DEBUG = env_bool("GAMEHUB_DEBUG", default=not IS_RENDER)

allowed_hosts = {
    host.strip()
    for host in os.getenv("GAMEHUB_ALLOWED_HOSTS", "127.0.0.1,localhost").split(",")
    if host.strip()
}
render_hostname = os.getenv("RENDER_EXTERNAL_HOSTNAME", "").strip()
if render_hostname:
    allowed_hosts.add(render_hostname)
ALLOWED_HOSTS = sorted(allowed_hosts)

trusted_origins = {
    origin.strip()
    for origin in os.getenv("GAMEHUB_CSRF_TRUSTED_ORIGINS", "").split(",")
    if origin.strip()
}
if render_hostname:
    trusted_origins.add(f"https://{render_hostname}")
CSRF_TRUSTED_ORIGINS = sorted(trusted_origins)

